def _route_note_for(commodity_name: str, ts_port: str | None, service_lane: str | None) -> str | None:
    """Three independent route-note triggers, all confirmed against
    reference/23's own AMW ground truth (no row seen combines more than
    one, but they'd join with " | " same as TAD-WMW-WEW's identical rule
    if a future file ever does): a recognized special-node commodity-
    group-name tag (reused verbatim from TAD-OEW-OMW's own table), a
    populated T/S Port, and a populated Service Lane."""
    parts = []
    special = SPECIAL_NODE_ROUTE_NOTES.get(commodity_name)
    if special:
        parts.append(special)
    if ts_port:
        parts.append(f"Rates are Subject to Transhipment Port: {ts_port}")
    if service_lane:
        parts.append(f"Rates are applicable for Vessel Service Lane: {service_lane}")
    return " | ".join(parts) if parts else None


def _expand_arbs_term(value: object) -> str | None:
    text = str(value or "").strip()
    return {"D": "Door"}.get(text, text or None)


def _raw_str_or_none(value: object) -> str | None:
    """Strip if it's a string, otherwise pass the cell's literal value
    through unchanged - a blank cell can be either "" or a true None in
    these raw files, and ground truth's own output preserves whichever
    one it actually is rather than normalizing both to the same thing."""
    return value.strip() if isinstance(value, str) else value


def _parse_decimal(text: str | None) -> Decimal | None:
    # A literal 0 is a real rate (confirmed: Origin ARBS has genuine $0
    # entries) - `if not text` would treat that falsy int as "no value"
    # and silently drop the row.
    if text is None or text == "":
        return None
    try:
        return Decimal(str(text).replace(",", "").strip())
    except InvalidOperation:
        return None


def _parse_date(text: str | None) -> date | None:
    if not text:
        return None
    try:
        return date.fromisoformat(str(text).strip())
    except ValueError:
        return None


def _parse_included_codes(text: str | None) -> list[str]:
    """Same authoritative literal comma-separated list as every other TAD
    lane - see tad_oew_omw.py's comment for why this bypasses
    INDIVIDUAL_CHARGE_CODES. Notably: EX.JP's own rows naturally carry a
    SHORTER list than the main sheet's rows (e.g. missing HEA/LSF) simply
    because each row's own column already says so - no special-casing
    needed for the Japan scope here or in a future phase."""
    if not text:
        return []
    return [c.strip().upper() for c in str(text).split(",") if c.strip()]


