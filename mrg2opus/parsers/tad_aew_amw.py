"""TAD FILING AEW AMW lane parser.

Same DATA-sheet-shaped raw layout as TAD-OEW-OMW/TAD-WMW-WEW (see those
modules and the project_tad_vba_tool_analysis memory) - two raw sheets,
"AEW" and "AMW", each its own Service Scope and own OPUS output. Real
differences confirmed against reference/2_OPUS/23_TAD FILING AEW AMW:

- **Multi-snapshot filings**: this folder ships TWO raw "AEW"/"AMW" files
  for the same nominal period at different rates - a rate correction
  issued mid-period. Ground truth files both as separate CMDT NOTE blocks,
  the earlier one's validity truncated to end the day before the later
  one's own validity starts. Handled generically by
  parsers/common/tad_snapshots.py (also wired into TAD-OEW-OMW/WMW-WEW).
- **AEW's own CMDT NOTE sheet is literally named "SRCHG"**, not "CMDT
  NOTE" like AMW's (and every other TAD lane) - see
  SCOPED_SHEET_NAME_OVERRIDES. AEW also has NO ROUTE NOTE sheet at all
  (confirmed: zero T/S Port/Service Lane/special-node rows this period) -
  SHEET_NAME_OVERRIDES' "ROUTE NOTE" name still applies to AMW, which does
  use the mechanism (same HAYDARPASA/MARPORT/EGALY special-node table as
  TAD-OEW-OMW's own OMW sheet, reused directly - see
  SPECIAL_NODE_ROUTE_NOTES import - plus a populated Service Lane column,
  combined the same way TAD-WMW-WEW's own _route_note_for() does).
- **D7 (OFT 45)**: the raw MRG never carries this rate slot directly for
  AEW/AMW, but ground truth's own RATES rows do have it populated - equal
  to OFT 40HC (D5) plus a fixed $700 add-on (confirmed: reference/23's own
  "Surcharges" reference sheet documents this add-on; every real GT row
  checked satisfies rate_45 == rate_40hc + 700 exactly). Off by default
  and user-toggleable (config.include_tad_d7/tad_d7_addon) - AEW/AMW only,
  never generated by TAD-OEW-OMW or TAD-WMW-WEW, and only for D/DR rows (a
  generated D/DG duplicate, see config.generate_tad_dg_duplicate, copies
  the same D7 rate across rather than recomputing it).

- **Origin ARBS** (from the raw "Origin ARBS" sheet, feeding the same
  ArbsRow/OPUS ARBS schema already used by CSE's Yangtze mechanism):
  - Both raw snapshot files carry byte-identical Origin ARBS content (no
    rate correction here) - only the FIRST occurrence is parsed, not
    merged like the dated RATES sheets.
  - `Per(*)` = a cargo-type-derived prefix (Dry General/Dry Dangerous->D,
    Reefer/Reefer Dry->R) + the rate column's own size digit (2/4/5/7 for
    the 20/40/HC/45 columns) - `CGO Type` is a flat "DR" constant
    regardless of cargo type (confirmed, not derived from CARGO_TYPE_MAP's
    own cgo_type element).
  - `Seq.` is left blank - CSE's own ARBS ground truth leaves it blank
    too; this filing's own raw sheet happens to reuse that column for a
    plain Service Scope label, not a real per-row sequence number.
  - **Over vs Via**: the raw sheet can carry TWO SEPARATE rows for the
    same Point + Cargo Type, each its own explicit (Over, Via) pair (e.g.
    CNBHY/Dry General has one row Over=CNYTN/Via=CNNSA and another
    Over=CNYTN/Via=CNYTN; THLKR/Dry General has one row Over=SGSIN/
    Via=SGSIN and another Over=THLCH/Via=<blank>) - these are genuinely
    different data rows, not one row needing synthesized alternates: Via
    is read straight off its own column, blank included. Row order
    overall is OUTER by rate-size column (20, then 40, then HC, then 45),
    INNER by raw row order - confirmed against ground truth's own layout.
  - Effective/Expiry dates aren't given per ARBS row at all - ground truth
    uses the filing's own OVERALL (untruncated) span, i.e. the earliest
    snapshot's start through the latest snapshot's end (2026-09-01 to -15
    here), not either individual snapshot's own truncated window.

- **The Japan-origin scope** arrives as its own separate raw file
  ("EX.JP AEW"/"EX.JP AMW"/"Origin ARBS - EX JAPAN") in the same 22-column
  DATA shape, and surfaces as two more run_multi() scopes (SCOPE_JP_AEW/
  SCOPE_JP_AMW) rather than being folded into the main two:
  - It files under its OWN commodity group, "FAK - JAPAN", with a
    different default code per sub-scope (AEW G0011, AMW G0001 -
    confirmed, and yes they genuinely differ).
  - Its own validity window (2026-09-01 to -30, a whole month vs the main
    scopes' fortnight) and its own SHORTER charge-code list (CAF/CSS/EFS/
    MBS - no HEA/LSF) come straight off its own rows' columns, so no
    special-casing is needed for either.
  - No D7: the OFT 45 add-on is AEW/AMW-only (the raw "Surcharges"
    reference sheet scopes it that way, and the Japan ground truth has no
    rate_45 anywhere) - see ScopeData.supports_d7.
  - AEW-Japan produces NO route notes at all (no T/S Port, Service Lane,
    or special-node tag on any of its rows); AMW-Japan produces 35, from
    the same HAYDARPASA/MARPORT special-node table as the main scopes.
  - Its ARBS is byte-identical to the copies bundled into the main files
    as "AEW ARBS JP"/"ORIGIN ARBS JP" (verified row-for-row) - emitted
    once here under the Japan scopes rather than duplicated, since the
    later per-file splitting step (see project_tad_vba_tool_analysis
    memory) is what assembles the real deliverables anyway.

  **On its ground truth**: unlike AEW/AMW POLLY.xlsx, JAPAN POLLY.xlsx is
  NOT a finished OPUS filing - it's the team's VBA tool caught at its
  DATA->RATES bulk-copy step: origin/destination Descriptions still blank,
  Commodity Note still holding the raw "CAF,CSS,EFS,MBS" CSV instead of
  the built note text, CMDT/Route Seq still blank, and 4 extra VBA working
  columns (Start Date, End Date, Lanes, cargo type) hanging off the end.
  Per the user's confirmed "full replacement, not a DATA-shaped
  intermediate" decision, this parser produces a COMPLETE OPUS output for
  the Japan scope like every other lane - so only the columns that ground
  truth actually derived are comparable, and the tests ignore the rest.

Known ground-truth inconsistencies in this one filing, all filing-prep
artifacts rather than derivable rules (each verified, each handled by
running the affected scope with its own MappingProfile in the tests):
the DG duplicate toggle was ON for the main AEW/AMW scopes but OFF for
the Japan ones, and the RFA child-date window differs three ways (AEW
2026-08-30, AMW 2026-08-19, Japan-AEW using the plain validity window and
Japan-AMW 2026-08-30) even though both are single filing-wide settings.
"""
